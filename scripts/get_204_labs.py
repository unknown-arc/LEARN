"""Generate the metadata the 204 (Computer Organization) site reads.

Run from anywhere:  python scripts/get_204_labs.py

Writes
  ACADEMIC/204/labs.json            -> only the LAB folders (name + folder)
  ACADEMIC/204/LAB-n/index.json     -> that lab's three groups of files:
        task        Task.txt (any letter case) in the lab folder, or null
        circuits    every *.circ file (Logisim), including nested ones
        other_files everything else, except the generated *.json files

Every path is relative to its LAB folder. The playground ignores nothing on
its own, so keep generated files (*.json) and tooling folders out of the lists
here.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUBJECT_DIR = ROOT / "ACADEMIC" / "204"

IGNORED_DIRS = {"playgrounds", "__pycache__", ".git"}
IGNORED_EXTENSIONS = {".json"}  # generated by this script
CIRCUIT_EXTENSION = ".circ"
TASK_NAME = "task.txt"

def is_lab(folder: Path) -> bool:
    return (
        folder.is_dir()
        and folder.name.startswith("LAB-")
        and folder.name.removeprefix("LAB-").isdigit()
    )


def lab_number(folder: Path) -> int:
    return int(folder.name.removeprefix("LAB-"))

def lab_files(folder: Path):
    """Every file inside a lab, as a sorted list, skipping ignored folders."""
    files = []
    for file in folder.rglob("*"):
        if not file.is_file():
            continue
        parts = file.relative_to(folder).parts
        if any(part in IGNORED_DIRS for part in parts):
            continue
        files.append(file)
    return sorted(files, key=lambda f: f.as_posix().lower())


def build_manifest(folder: Path) -> dict:
    task = None
    circuits = []
    others = []

    for file in lab_files(folder):
        rel = file.relative_to(folder).as_posix()
        ext = file.suffix.lower()

        if ext in IGNORED_EXTENSIONS:
            continue
        if file.parent == folder and file.name.lower() == TASK_NAME:
            task = task or rel
        elif ext == CIRCUIT_EXTENSION:
            circuits.append(rel)
        else:
            others.append(rel)

    return {
        "name": folder.name,
        "folder": folder.name,
        "task": task,
        "circuits": circuits,
        "other_files": others,
    }


def main():
    if not SUBJECT_DIR.is_dir():
        raise FileNotFoundError(f"Subject directory not found: {SUBJECT_DIR}")

    folders = [
        f for f in SUBJECT_DIR.iterdir()
        if f.is_dir() and f.name.startswith("LAB-") and lab_number(f) is not None
    ]

    folders = [f for f in SUBJECT_DIR.iterdir() if is_lab(f)]
    folders.sort(key=lab_number)

    labs = [{"name": f.name, "folder": f.name} for f in folders]
    (SUBJECT_DIR / "labs.json").write_text(
        json.dumps(labs, indent=2) + "\n", encoding="utf-8"
    )
    print(f"204: found {len(labs)} labs")
    print(f"Wrote {(SUBJECT_DIR / 'labs.json').relative_to(ROOT)}")

    for folder in folders:
        manifest = build_manifest(folder)
        path = folder / "index.json"
        path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        print(
            f"  {folder.name}: task={manifest['task'] or 'none'}, "
            f"circ={len(manifest['circuits'])}, other={len(manifest['other_files'])}"
        )

    print("Done. Commit labs.json and the LAB-*/index.json files.")


if __name__ == "__main__":
    main()
